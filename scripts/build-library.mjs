// Generates extension/library.js from assets/catalog.json (the single source of truth).
import fs from 'node:fs';
import {opaqueShare} from './png-coverage.mjs';
const catalog=JSON.parse(fs.readFileSync('assets/catalog.json','utf8'));
const runtime=fs.readFileSync('scripts/library-runtime.js','utf8');
for(const e of catalog)for(const [k,v] of Object.entries(e.variants)){
  const p=k==='original'?v.preview:v.path;
  if(p&&!fs.existsSync('extension/'+p))throw Error(`${e.id}/${k}: missing ${p}`);
}
// An original favicon that is already a solid shape (square, rounded square, circle) fills the
// settings-page frame like the other versions; a bare glyph on transparency gets a margin instead.
for(const e of catalog){const o=e.variants.original;if(o?.preview)o.fill=opaqueShare('extension/'+o.preview)>=0.75}
fs.writeFileSync('extension/library.js','// Generated by scripts/build-library.mjs from assets/catalog.json. Do not edit.\nconst ICON_LIBRARY=Object.freeze('+JSON.stringify(catalog,null,2)+');\n'+runtime);
console.log(`library.js: ${catalog.length} sites, ${catalog.filter(e=>e.variants.optimized).length} optimized`);
